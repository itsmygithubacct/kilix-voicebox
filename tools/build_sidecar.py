#!/usr/bin/env python3
"""Orchestrate one sidecar build: identity, producer, collector, consumer.

This is the missing normal-build bridge. It generates the invocation identity
at the start of the build, outside the source tree, binds the actual clean
product commit and tree, hands every selected input to the collector
explicitly, and then carries that same identity and the producer's real
selected-input notice directory to the consumer **before** the stage is
cleaned up. Nothing here discovers an authority: an identity that is not
generated by this invocation, or an input that is not named by the caller, is
a refusal and never a default.

The producer runs exactly once per build. The Tauri hook calls this tool
rather than repeating it, and a standalone Tauri release build reaches the
same path instead of packaging whatever is already lying in the tree.

Exit status: 0 built and verified, 2 refused, 3 missing explicit inputs.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))

import sidecar_authority as authority  # noqa: E402
from verify_sidecar_provenance import BRIDGE  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
COLLECTOR = ROOT / 'scripts/build-server.sh'
PRODUCER = ROOT / 'kilix_voicebox_backend/build_binary.py'
NOTICES = 'selected-inputs'
HANDOFF = 'sidecar-outputs'

# Each selected input, its command-line flag and the variable a build route may
# supply it through. None has a default: a workspace path baked in here would
# quietly decide what a release contains.
INPUTS = (
    ('stage_root', '--stage-root', 'VOICEBOX_SIDECAR_STAGE_ROOT',
     'an existing directory outside the checkout to build in'),
    ('python_executable', '--python-executable', 'VOICEBOX_SIDECAR_PYTHON',
     'the selected CPython 3.12.8 executable'),
    ('voice_source', '--voice-source', 'VOICEBOX_SIDECAR_VOICE_SOURCE',
     'the selected Voice source checkout'),
    ('transcribe_source', '--transcribe-source', 'VOICEBOX_SIDECAR_TRANSCRIBE_SOURCE',
     'the selected transcribe source checkout'),
    ('transcribe_wheel', '--transcribe-wheel', 'VOICEBOX_SIDECAR_TRANSCRIBE_WHEEL',
     'the selected transcribe wheel'),
    ('wheelhouse', '--wheelhouse', 'VOICEBOX_SIDECAR_WHEELHOUSE',
     'the selected 35-wheel wheelhouse'),
    ('python_home', '--python-home', 'VOICEBOX_SIDECAR_PYTHON_HOME',
     'the selected Python home'),
)


class Refused(Exception):
    pass


class MissingInputs(Exception):
    pass


def git(*arguments):
    result = subprocess.run(('git', '-C', str(ROOT), *arguments), check=False,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if result.returncode:
        raise Refused('git ' + ' '.join(arguments) + ' failed: ' + result.stderr.strip())
    return result.stdout.strip()


def clean_source_identity():
    """The actual product commit and tree, refused unless the checkout is clean."""
    dirty = git('status', '--porcelain')
    if dirty:
        raise Refused('the product checkout is not clean; the sidecar must be built from '
                      'an exact committed source:\n' + dirty)
    return git('rev-parse', 'HEAD'), git('rev-parse', 'HEAD^{tree}')


def selected_inputs(options):
    """Every input, from the flag or its variable, with each omission named."""
    resolved = {}
    missing = []
    if not getattr(options, 'platform', None):
        missing.append('Rust host tuple (--platform or VOICEBOX_SIDECAR_PLATFORM)')
    for name, flag, variable, description in INPUTS:
        value = getattr(options, name) or os.environ.get(variable)
        if not value:
            missing.append('%s (%s or %s)' % (description, flag, variable))
            continue
        path = Path(value)
        if not path.is_absolute():
            raise Refused('selected input %s must be an absolute path: %s' % (flag, value))
        resolved[name] = path
    if missing:
        raise MissingInputs('this build has no explicit ' + '; no explicit '.join(missing))
    return resolved


def run_build(options):
    # Missing explicit inputs are reported before anything else, so a caller
    # that supplied none is told what to supply rather than what is dirty.
    inputs = selected_inputs(options)
    commit, tree = clean_source_identity()
    # The nonce is generated here, at the start of this build, and never taken
    # from a record that already exists.
    build_id = secrets.token_hex(16)
    stage_root = inputs['stage_root']
    if not stage_root.is_dir() or stage_root.is_symlink():
        raise Refused('the stage root must be an existing directory that is not a link: '
                      + str(stage_root))
    if stage_root == ROOT or ROOT in stage_root.parents or stage_root.is_relative_to(ROOT):
        raise Refused('the stage root must be outside the source checkout: ' + str(stage_root))
    stage = stage_root / ('stage-' + build_id)
    private_home = stage_root / ('home-' + build_id)
    if stage.exists() or private_home.exists():
        raise Refused('this build identity is already in use: ' + build_id)
    private_home.mkdir(mode=0o700)

    collector = [str(COLLECTOR), '--build-id', build_id, '--stage-dir', str(stage),
                 '--python-executable', str(inputs['python_executable']),
                 '--producer', str(options.producer or PRODUCER),
                 '--voice-source', str(inputs['voice_source']),
                 '--transcribe-source', str(inputs['transcribe_source']),
                 '--transcribe-wheel', str(inputs['transcribe_wheel']),
                 '--wheelhouse', str(inputs['wheelhouse']),
                 '--python-home', str(inputs['python_home']),
                 '--private-home', str(private_home),
                 # The stage holds the notices the consumer still needs.
                 '--keep-stage']
    print('voicebox: building sidecar %s from %s' % (build_id, commit[:12]), flush=True)
    produced = subprocess.run(collector, cwd=ROOT, check=False)
    if produced.returncode:
        raise Refused('the sidecar build failed; its stage is retained at ' + str(stage))

    # The same identity this build generated, carried straight through. The
    # handoff the producer wrote is used as a cross-check, not as the authority.
    # -B for the same reason as the gate's own orchestrator child: -I implies -E,
    # so only the command line can keep bytecode out of the checkout.
    gate = [sys.executable, '-I', '-B', str(ROOT / 'tools/prepare_sidecar_resources.py'),
            '--binary', str(options.binary_for(build_id)),
            '--provenance', str(options.provenance_for(build_id)),
            '--staged-inputs', str(stage / NOTICES),
            '--input-manifest', str(ROOT / '.kilix-import/sidecar-inputs.json'),
            '--uv-lock', str(ROOT / 'uv.lock'),
            '--build-id', build_id, '--handoff', str(stage / HANDOFF),
            '--source-commit', commit, '--source-tree', tree]
    verified = subprocess.run(gate, cwd=ROOT, check=False)
    if verified.returncode:
        raise Refused('the produced sidecar did not verify; its stage is retained at '
                      + str(stage) + ' and no resource set is publishable')

    # Carried for the packaging capability: the identities this invocation
    # actually verified, and a private location outside the checkout to mint it
    # in. Recorded rather than rediscovered, so the capability cannot be bound
    # to anything this build did not just prove.
    options.verified = {'build_id': build_id, 'source_commit': commit,
                        'source_tree': tree, 'stage_root': stage_root}

    # Only a complete, verified build cleans up after itself.
    shutil.rmtree(stage, ignore_errors=False)
    shutil.rmtree(private_home, ignore_errors=False)
    print(json.dumps({'status': 'built', 'build_id': build_id, 'source_commit': commit},
                     sort_keys=True))
    return build_id


RESOURCE_RECEIPT = ROOT / 'tauri/src-tauri/resources/sidecar/RESOURCES.json'


def issue_packaging_authority(options, build_id):
    """Mint the single-use capability for this invocation's packaging child."""
    verified = getattr(options, 'verified', None)
    if not verified or verified.get('build_id') != build_id:
        raise authority.AuthorityError(
            'this invocation did not record a verified build to authorize')
    try:
        receipt = json.loads(RESOURCE_RECEIPT.read_text(encoding='utf-8'))
        resources = receipt['resources']
    except (OSError, ValueError, KeyError) as error:
        raise authority.AuthorityError(
            'the resource receipt could not be read to bind the capability: %s' % error)
    if not isinstance(resources, list):
        raise authority.AuthorityError('the resource receipt resource list is malformed')
    return authority.issue(
        verified['stage_root'] / ('authority-' + build_id),
        build_id=build_id,
        source_commit=verified['source_commit'],
        source_tree=verified['source_tree'],
        platform=options.platform,
        binary=options.binary_for(build_id),
        provenance=options.provenance_for(build_id),
        receipt=RESOURCE_RECEIPT,
        resources=resources,
        root=ROOT)


class Options(argparse.Namespace):
    platform = None
    verified = None

    def binary_for(self, _build_id):
        return ROOT / 'tauri/src-tauri/binaries' / ('voicebox-server-' + self.platform)

    def provenance_for(self, build_id):
        return Path(str(self.binary_for(build_id)) + '.provenance.json')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for name, flag, _variable, description in INPUTS:
        parser.add_argument(flag, dest=name, default=None, help=description)
    parser.add_argument('--producer', default=None,
                        help='the producer script; defaults to the checked-in one')
    parser.add_argument('--platform', default=os.environ.get('VOICEBOX_SIDECAR_PLATFORM'),
                        help='Rust host tuple naming the installed sidecar')
    parser.add_argument('--package', default=None,
                        help='shell command to run once the gate has passed')
    options = parser.parse_args(argv, namespace=Options())
    capability = None
    try:
        build_id = run_build(options)
        if options.package:
            # The packaging child is authorized by a single-use capability this
            # live invocation mints, held outside the checkout and revoked as
            # soon as packaging ends. An inherited id or boolean is no longer
            # authority for anything: a stale environment now reaches a gate
            # that has nothing to consume.
            capability = issue_packaging_authority(options, build_id)
            environment = dict(os.environ,
                               VOICEBOX_SIDECAR_PLATFORM=options.platform)
            environment.pop('VOICEBOX_SIDECAR_GATE_PASSED', None)
            environment[authority.VARIABLE] = str(capability)
            packaged = subprocess.run(options.package, shell=True, cwd=ROOT, env=environment,
                                      check=False)
            if packaged.returncode:
                return 2
    except MissingInputs as error:
        print('voicebox: the sidecar build refuses: ' + str(error), file=sys.stderr)
        print('voicebox: see docs/developer/sidecar-build.md; nothing is chosen by default',
              file=sys.stderr)
        print('voicebox: ' + BRIDGE, file=sys.stderr)
        return 3
    except Refused as error:
        print('voicebox: the sidecar build refuses: ' + str(error), file=sys.stderr)
        return 2
    except authority.AuthorityError as error:
        print('voicebox: the sidecar build refuses: could not mint a packaging '
              'authority: ' + str(error), file=sys.stderr)
        return 2
    finally:
        # Completion, refusal, cancellation and interruption all end the
        # capability's life. Nothing survives this invocation to authorize a
        # later package build.
        if capability is not None:
            authority.revoke(capability)
            directory = Path(capability).parent
            try:
                if not any(directory.iterdir()):
                    directory.rmdir()
            except OSError:
                pass
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
